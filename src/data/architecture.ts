import type { ArchitectureLayer } from '@/types'

function x(labels: string[]): number[] {
  const widths = labels.map((l) => Math.max(90, l.length * 7 + 28))
  const positions: number[] = []
  let cursor = 20
  for (const w of widths) {
    positions.push(cursor)
    cursor += w + 14
  }
  return positions
}

function nodes(
  layer: string,
  items: Array<{ id: string; label: string; type: 'service' | 'data' | 'gateway' | 'platform' | 'security' | 'integration'; connections?: string[] }>,
): ArchitectureLayer['nodes'] {
  const xs = x(items.map((i) => i.label))
  return items.map((item, i) => ({
    id: item.id,
    label: item.label,
    x: xs[i],
    y: 20,
    width: Math.max(90, item.label.length * 7 + 28),
    height: 36,
    type: item.type,
    connections: item.connections,
  }))
}

